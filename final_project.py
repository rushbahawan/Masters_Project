def preprocess_pathway_clr(df_raw, sample_ids, prevalence=0.10):
    pathway_T = df_raw.set_index(df_raw.columns[0]).T
    pathway_T.index.name = 'sample_name'
    pathway_sub = pathway_T.loc[pathway_T.index.isin(sample_ids)].fillna(0)
    pathway_sub = pathway_sub.loc[:, (pathway_sub > 0).mean(axis=0) >= prevalence]
    pathway_sub = pathway_sub.div(pathway_sub.sum(axis=1), axis=0)
    pathway_clr = clr_transform(pathway_sub)
    sel = VarianceThreshold(threshold=0.001)
    arr = sel.fit_transform(pathway_clr)
    return arr, pathway_sub.index

