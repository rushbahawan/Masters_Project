# Cell 10 - statistical analysis
p_values    = []
odds_ratios = []

for col in X_pd.columns:
    x = X_pd[col].values.reshape(-1, 1)
    lr = LogisticRegression(class_weight='balanced', random_state=42, max_iter=1000)
    lr.fit(x, y_pd)
    odds_ratio = np.exp(lr.coef_[0][0])

    null_prob  = np.full(len(y_pd), y_pd.mean())
    null_loss  = sk_log_loss(y_pd, null_prob)
    model_loss = sk_log_loss(y_pd, lr.predict_proba(x)[:, 1])
    lr_stat    = 2 * len(y_pd) * (null_loss - model_loss)
    p          = 1 - chi2.cdf(lr_stat, df=1)

    p_values.append(p)
    odds_ratios.append(odds_ratio)

reject, p_adj, _, _ = multipletests(p_values, method='fdr_bh')

stats_results = pd.DataFrame({
    'species':     feature_names,
    'odds_ratio':  odds_ratios,
    'p_value':     p_values,
    'p_adjusted':  p_adj,
    'significant': reject
}).sort_values('p_adjusted')

