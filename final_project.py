# Cell 6 - transformations
def clr_transform(df):
    X = df.copy().astype(float)
    X = X.replace(0, np.nan)
    delta = 0.65 * X.min(axis=1, skipna=True)
    for col in X.columns:
        X[col] = X[col].fillna(delta)
    log_X = np.log(X)
    clr = log_X.subtract(log_X.mean(axis=1), axis=0)
    return clr

def preprocess_microbiome_clr(df, prevalence=0.10):
    X = df.fillna(0)
    X = X.loc[:, (X > 0).mean(axis=0) >= prevalence]
    X = X.div(X.sum(axis=1), axis=0)
    X_clr = clr_transform(X)
    sel = VarianceThreshold(threshold=0.001)
    arr = sel.fit_transform(X_clr)
    return pd.DataFrame(arr, index=X_clr.index,
                        columns=X_clr.columns[sel.get_support()])

