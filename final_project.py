def prepare_metadata(meta_source, label_col, meta_cols):
    df = meta_source[['sample_name', label_col] + meta_cols].copy()
    df = df.set_index('sample_name')

    print(f"Class balance — Class 0: {(df[label_col]==0).sum()} | Class 1: {(df[label_col]==1).sum()}")

    numeric_cols   = df.drop(columns=label_col).select_dtypes(
        include=[np.number]).columns.tolist()
    categoric_cols = df.drop(columns=label_col).select_dtypes(
        exclude=[np.number]).columns.tolist()

    for col in numeric_cols:
        n_miss = df[col].isnull().sum()
        if n_miss > 0:
            print(f"  Imputing {col}: {n_miss} missing → median ({df[col].median():.2f})")
            df[col] = df[col].fillna(df[col].median())

    le = LabelEncoder()
    for col in categoric_cols:
        n_miss = df[col].isnull().sum()
        if n_miss > 0:
            mode_val = df[col].mode()[0]
            print(f"  Imputing {col}: {n_miss} missing → mode ({mode_val})")
            df[col] = df[col].fillna(mode_val)
        df[col] = le.fit_transform(df[col].astype(str))

    X = df.drop(columns=label_col).values
    y = df[label_col].values
    return X, y, df.drop(columns=label_col).columns.tolist()

