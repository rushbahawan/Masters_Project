# Cell 28 — bootstrap statistical comparison
def bootstrap_compare(y_true, probs1, probs2, name1, name2, n=1000):
    diffs = []
    rng = np.random.default_rng(42)
    for _ in range(n):
        idx = rng.choice(len(y_true), len(y_true), replace=True)
        try:
            diffs.append(roc_auc_score(y_true[idx], probs1[idx]) -
                         roc_auc_score(y_true[idx], probs2[idx]))
        except: pass
    lo, hi = np.percentile(diffs, [2.5, 97.5])
    print(f"{name1} vs {name2}: diff={np.mean(diffs):.4f}, "
          f"95%CI=[{lo:.4f},{hi:.4f}], Sig={'YES' if lo > 0 else 'NO'}")

